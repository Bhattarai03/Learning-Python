# Using walrus operator
# The walrus operator (:=) in Python is a shorthand for assigning and using a value at the same time — introduced in Python 3.8.

if (n:=len([1,2,3,4,5,6,7]))>3:    # It is widely used in today world because in a single code of line ,multiple operation can be done.
    print(f"List is too long .The list  contains more than 3 element i.e {n} element")
